"""``node_modules`` is never committed, as a folder or as a link.

``node_modules/`` in ``.gitignore`` matches only a folder, so a symlink named
``node_modules`` (one worktree sharing another's install) slipped into a
squash merge. ``node_modules`` without the slash ignores both.
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]


def test_gitignore_ignores_node_modules_as_a_folder_or_a_link() -> None:
    lines = (ROOT / ".gitignore").read_text().splitlines()
    assert "node_modules" in lines


@pytest.mark.skipif(
    shutil.which("git") is None or not (ROOT / ".git").exists(), reason="not a git checkout",
)
def test_node_modules_is_not_tracked() -> None:
    tracked = subprocess.run(
        ["git", "ls-files", "--", "node_modules"],
        cwd=ROOT, capture_output=True, text=True, check=True,
    ).stdout
    assert tracked == ""
